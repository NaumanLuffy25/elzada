import { NextRequest, NextResponse } from "next/server";
import { evaluateRag, evaluateClassifier, type ClassifierMetrics } from "@/lib/evaluation";
import { generateAnswer } from "@/lib/rag";
import type { ModelBundle } from "@/lib/ml-classifier";
import {
  CATEGORY_DISPLAY,
  CATEGORY_ORDER,
  CLASSIFIER_TARGETS,
  CLASSIFIER_TEST_SET,
  RAG_EVAL_FIXTURES,
  type RagEvalExample,
} from "@/lib/eval-fixtures";

export const runtime = "nodejs";

/**
 * Runtime evaluation endpoint.
 *
 * - `parts=all` (default) → RAG metrics + classifier metrics (back-compat).
 * - `parts=classifier`    → classifier metrics only (fast; used by the
 *                           Intent Classifier panel so it never waits on the
 *                           RAG pipeline).
 * - `parts=rag`           → RAG metrics only.
 *
 * The classifier section ALWAYS reports measured values produced by running the
 * trained model over the held-out test set in `lib/eval-fixtures.ts`, plus the
 * project target values under a clearly separate `targets` key. Targets are
 * never mixed into `metrics`.
 */
export async function GET(req: NextRequest) {
  if (!checkAuth(req)) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const url = new URL(req.url);
  const parts = url.searchParams.get("parts") ?? "all";

  // ---- RAG -----------------------------------------------------------------
  let rag: Awaited<ReturnType<typeof evaluateRag>> | undefined;
  if (parts === "all" || parts === "rag") {
    const sample = Math.min(50, Number(url.searchParams.get("sample") ?? RAG_EVAL_FIXTURES.length));
    rag = await evaluateRag(RAG_EVAL_FIXTURES.slice(0, sample), generateAnswer);
  }

  // ---- Classifier ----------------------------------------------------------
  let classifier: ClassifierPayload | undefined;
  if (parts === "all" || parts === "classifier") {
    classifier = await buildClassifierPayload();
  }

  return NextResponse.json({ rag, classifier, generatedAt: new Date().toISOString() });
}

export async function POST(req: NextRequest) {
  if (!checkAuth(req)) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  const body = await req.json().catch(() => ({}));
  const fixtures: RagEvalExample[] = Array.isArray(body?.fixtures) ? body.fixtures : RAG_EVAL_FIXTURES;
  const rag = await evaluateRag(fixtures, generateAnswer);
  return NextResponse.json({ rag, generatedAt: new Date().toISOString() });
}

/* -------------------------------------------------------------------------- */
/* Classifier payload                                                         */
/* -------------------------------------------------------------------------- */

export type ClassifierPayload =
  | {
      available: false;
      reason: "model-not-trained";
      note: string;
      testSetSize: number;
      targets: typeof CLASSIFIER_TARGETS;
      generatedAt: string;
    }
  | {
      available: true;
      /** Where the measured numbers come from. */
      measuredOn: { count: number; description: string };
      /** Project goals — never measured values. */
      targets: typeof CLASSIFIER_TARGETS;
      /** Measured metrics, derived from the confusion matrix. */
      metrics: ClassifierMetrics & {
        perCategory: { key: string; label: string }[];
      };
      model: { version: string; trainedAt: string; vocabSize: number; labels: string[] };
      report: string;
      generatedAt: string;
    };

async function buildClassifierPayload(): Promise<ClassifierPayload> {
  const generatedAt = new Date().toISOString();
  const testSetSize = CLASSIFIER_TEST_SET.length;

  let model: ModelBundle | null = null;
  try {
    // Lazy import so the JSON never lands in the client bundle.
    // @ts-ignore – generated by `npm run train`
    const mod: any = await import("@/lib/classifier.model.json").catch(() => null);
    model = (mod?.default ?? mod) as ModelBundle | null;
  } catch {
    model = null;
  }

  const trained =
    !!model &&
    model.vocabSize > 0 &&
    !!model.vocab &&
    Object.keys(model.vocab).length > 0 &&
    !String(model.version ?? "").includes("placeholder");

  if (!trained || !model) {
    return {
      available: false,
      reason: "model-not-trained",
      note:
        "The bundled classifier is a placeholder with an empty vocabulary. Run `npm run train` " +
        "to build a real model, then `npm run evaluate` to reproduce these numbers.",
      testSetSize,
      targets: CLASSIFIER_TARGETS,
      generatedAt,
    };
  }

  const metrics = evaluateClassifier(model, CLASSIFIER_TEST_SET);

  return {
    available: true,
    measuredOn: {
      count: testSetSize,
      description: "held-out test set (disjoint from training data), lib/eval-fixtures.ts",
    },
    targets: CLASSIFIER_TARGETS,
    metrics: {
      ...metrics,
      // Stable display order for the dashboard table.
      perCategory: CATEGORY_ORDER.map((key) => ({ key, label: CATEGORY_DISPLAY[key] })),
    },
    model: {
      version: model.version,
      trainedAt: model.trainedAt,
      vocabSize: model.vocabSize,
      labels: model.labels,
    },
    report: metrics.report,
    generatedAt,
  };
}

function checkAuth(req: NextRequest) {
  const token = req.headers.get("x-admin-token") ?? new URL(req.url).searchParams.get("token");
  return token && token === process.env.ADMIN_DASHBOARD_TOKEN;
}
